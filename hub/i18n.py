"""Lights Out window text in the seven languages Bodycam itself ships.

The game's localization lives in Content/Localization/Game/<code>/Game.locres for exactly
these cultures: de, en, es, fr, pt, ru, zh : so the hub offers the same seven and nothing
else. The player picks one on first run (LanguageDialog in app.py); the choice is stored
as "language" in state.json and can be changed later with the "Language…" button. It only
affects the hub window: Bodycam keeps its own language setting, and the gamemodes' in-game
text is localized separately (per-gamemode loc files merged into the game's .locres by the
pak builder).

Usage:  from .i18n import t;  t("install")  ->  "Install" / "Installieren" / …
        t("game_line", path=...)            ->  formatted with str.format
Strings are looked up in the current language, then English, then the key itself, so a
missing translation can never crash the window.

Translations were written by Claude (machine quality, not native-reviewed). Corrections
belong here : every language has the same key set (tests/test_hub.py checks it).
"""
import locale
import math
import os
import sys

# (code, native name) : the order the dialog lists them in
LANGUAGES = [
    ("en", "English"),
    ("de", "Deutsch"),
    ("es", "Español"),
    ("fr", "Français"),
    ("pt", "Português"),
    ("ru", "Русский"),
    ("zh", "中文"),
]
CODES = [c for c, _ in LANGUAGES]
DEFAULT = "en"

_current = DEFAULT


def set_language(code: str) -> str:
    """Make `code` current (falls back to English for an unknown code). Returns what was set."""
    global _current
    _current = code if code in STRINGS else DEFAULT
    return _current


def get_language() -> str:
    return _current


def name_of(code: str) -> str:
    for c, n in LANGUAGES:
        if c == code:
            return n
    return code


def tr(code: str, key: str, **kw) -> str:
    """Translate `key` into a specific language (used by the language dialog's live preview)."""
    s = STRINGS.get(code, {}).get(key) or STRINGS[DEFAULT].get(key) or key
    return s.format(**kw) if kw else s


def t(key: str, **kw) -> str:
    """Translate `key` into the current language."""
    return tr(_current, key, **kw)


# ---------------------------------------------------------------- counts
# A COUNT NEXT TO A NOUN needs the noun's form for that count ("1 more placement match", not
# "1 more placement matches"), and the seven languages do not agree on how many forms there are.
# English, German, Spanish and Portuguese have two: 1, and everything else. French puts 0 with 1.
# Russian has three for whole numbers: 1, 21, 31...; 2-4, 22-24...; and the rest. Chinese has
# one. So STRINGS keeps each such string's GENERAL form, the one most counts take, which keeps the
# key set the same in every language and keeps t() working. PLURALS (at the end of this file)
# holds only the forms that differ from it, and tn() picks by count. The web UI's HubUI.tn mirrors
# plural_form; tests/test_i18n_plurals.py holds the two to the same answer.
def plural_form(code: str, n) -> str:
    """The CLDR cardinal category of `n` in language `code`: "one", "few" or "other".

    "other" stands in for Russian "many" too, because that is the general form STRINGS holds.
    Anything that is not a whole number (the dash for a total not known yet) is "other"."""
    if n is None or isinstance(n, bool):
        return "other"
    try:
        v = float(n)
    except (TypeError, ValueError):
        return "other"
    if not math.isfinite(v) or v != int(v):
        return "other"
    v = abs(int(v))
    if code == "ru":
        if v % 10 == 1 and v % 100 != 11:
            return "one"
        if 2 <= v % 10 <= 4 and not 12 <= v % 100 <= 14:
            return "few"
        return "other"
    if code == "fr":
        return "one" if v <= 1 else "other"
    if code == "zh":
        return "other"
    return "one" if v == 1 else "other"


def trn(code: str, key: str, n, **kw) -> str:
    """Translate `key` for a count of `n` into a specific language, formatted with n=n.

    A form a language does not have falls back to ITS OWN general form, never to English's."""
    code = code if code in STRINGS else DEFAULT
    form = plural_form(code, n)
    s = PLURALS.get(code, {}).get(key, {}).get(form) if form != "other" else None
    s = s or STRINGS[code].get(key) or STRINGS[DEFAULT].get(key) or key
    return s.format(n=n, **kw)


def tn(key: str, n, **kw) -> str:
    """t() for a string that counts something: the noun agrees with `n` in every language."""
    return trn(_current, key, n, **kw)


# ---------------------------------------------------------------- system language
# Windows primary language ids (LANGID & 0x3FF) for the seven cultures
_PRIMARY = {0x09: "en", 0x07: "de", 0x0A: "es", 0x0C: "fr", 0x16: "pt", 0x19: "ru", 0x04: "zh"}
# locale names as Windows' C runtime spells them ("German_Germany") and as POSIX does ("de_DE")
_WINDOWS_NAMES = {"english": "en", "german": "de", "spanish": "es", "french": "fr",
                  "portuguese": "pt", "russian": "ru", "chinese": "zh"}


def _from_locale_string(s):
    if not s:
        return None
    s = s.strip().lower()
    head = s.split("_")[0].split("-")[0].split(".")[0]
    if head in CODES:
        return head
    for name, code in _WINDOWS_NAMES.items():
        if s.startswith(name):
            return code
    return None


def detect_system_language() -> str:
    """Best guess for the first-run dialog's preselected entry; never raises."""
    if sys.platform == "win32":
        try:
            import ctypes
            langid = int(ctypes.windll.kernel32.GetUserDefaultUILanguage())
            code = _PRIMARY.get(langid & 0x3FF)
            if code:
                return code
        except Exception:
            pass
    candidates = [os.environ.get("LC_ALL"), os.environ.get("LC_MESSAGES"), os.environ.get("LANG")]
    try:
        candidates.append((locale.getlocale() or (None,))[0])
    except Exception:
        pass
    for cand in candidates:
        code = _from_locale_string(cand)
        if code:
            return code
    return DEFAULT


def font_family(code: str):
    """A font family to prefer for this language, or None for the system default.
    Tk falls back per glyph on Windows anyway; this just keeps Chinese consistent."""
    return "Microsoft YaHei UI" if code == "zh" else None


